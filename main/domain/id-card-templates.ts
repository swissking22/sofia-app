export function wizardDesign(input: {
  orientation: CardOrientation
  starting: 'blank' | 'classic' | 'modern' | 'minimal' | 'branding'
  fields: string[]
}): CardDesign {
  let design: CardDesign
  if (input.starting === 'classic') design = theHeritageDesign()
  else if (input.starting === 'modern') design = theAcademicDesign()
  else if (input.starting === 'minimal') design = theSignatureDesign()
  else if (input.starting === 'branding') design = theHeritageDesign()
  else design = blankTemplate(input.orientation)

  if (input.orientation !== design.orientation) {
    if (input.orientation === 'portrait') design = classicUniversityVertical()
    else if (input.starting === 'blank') design = blankTemplate('landscape')
  }

  const fieldToIds: Record<string, string[]> = {
    name: ['name'],
    student_id: ['id', 'id_label', 'id_value', 'barcode'],
    photo: ['photo'],
    class: ['class_label', 'class_value', 'fields', 'meta'],
    department: ['dept_label', 'dept_value'],
    dob: [],
    gender: [],
    academic_year: ['year', 'back_year'],
    qr: ['qr', 'verify'],
    barcode: ['barcode'],
  }
  const keep = new Set<string>(['hdr', 'logo', 'school_name', 'school', 'footer', 'web', 'border', 'white', 'accent', 'panel', 'vert_student', 'guide', 'line', 'back_hdr', 'back_title', 'back_foot', 'sig', 'sig_label', 'expiry', 'back_info'])
  for (const f of input.fields) {
    for (const id of fieldToIds[f] || []) keep.add(id)
  }
  if (input.fields.length) {
    design.elements = design.elements.filter(
      (e) => keep.has(e.id) || input.starting === 'blank'
    )
  }
  return design
}
